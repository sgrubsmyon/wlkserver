def strip_comments(text: str) -> str:
    """Remove `--` comments outside single-quoted strings."""
    out = []
    for line in text.splitlines():
        quote = False
        cut = len(line)
        for index, char in enumerate(line):
            if char == "'":
                quote = not quote
            elif not quote and line.startswith("--", index):
                cut = index
                break
        out.append(line[:cut])
    return "\n".join(out)


def split_top_level(body: str) -> list[str]:
    """Split a CREATE TABLE body on commas that are not inside parentheses."""
    parts, depth, current, quote = [], 0, [], False
    for char in body:
        if char == "'":
            quote = not quote
        if not quote:
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
            elif char == "," and depth == 0:
                parts.append("".join(current).strip())
                current = []
                continue
        current.append(char)
    if "".join(current).strip():
        parts.append("".join(current).strip())
    return parts


def parse_ddl(text: str):
    tables, order = {}, []
    for match in re.finditer(r"CREATE TABLE `?(\w+)`?\s*\((.*?)\)\s*ENGINE", text, re.S):
        name, body = match.group(1), match.group(2)
        columns, constraints = [], []
        for entry in split_top_level(body):
            entry = " ".join(entry.split())
            upper = entry.upper()
            if upper.startswith(("PRIMARY KEY", "FOREIGN KEY", "UNIQUE", "KEY", "CONSTRAINT", "INDEX")):
                constraints.append(entry)
                continue
            column, _, rest = entry.partition(" ")
            columns.append((column.strip("`"), rest.strip()))
        tables[name] = {"columns": columns, "constraints": constraints}
        order.append(name)
    for match in re.finditer(
        r"ALTER TABLE `?(\w+)`? ADD FOREIGN KEY \(([^)]*)\) REFERENCES `?(\w+)`?\(([^)]*)\)",
        text,
    ):
        table, cols, ref_table, ref_cols = match.groups()
        tables[table]["constraints"].append(
            f"FOREIGN KEY ({cols}) REFERENCES {ref_table}({ref_cols})"
        )
    return tables, order


def flags(rest: str) -> str:
    notes = []
    if "NOT NULL" in rest.upper():
        notes.append("NOT NULL")
    default = re.search(r"DEFAULT\s+('(?:[^']|'')*'|\S+)", rest, re.I)
    if default:
        notes.append(f"default {default.group(1)}")
    if "AUTO_INCREMENT" in rest.upper():
        notes.append("auto increment")
    return ", ".join(notes)


def type_of(rest: str) -> str:
    return re.match(r"[A-Za-z]+(\([^)]*\))?(\s+UNSIGNED)?", rest).group(0)


def main() -> None:
    text = strip_comments(DDL.read_text(encoding="utf-8"))
    tables, order = parse_ddl(text)

    out = [INTRO, "## Tables", ""]
    for name in order:
        purpose = PURPOSE.get(name, "TODO: describe this table.")
        out += [f"- [`{name}`](#{name}) - {purpose}"]

    for name in order:
        table = tables[name]
        out += ["", f"## {name}", "", PURPOSE.get(name, "TODO: describe this table."), ""]
        rows = [(column, type_of(rest), flags(rest)) for column, rest in table["columns"]]
        out += ["| Column | Type | Notes |", "|---|---|---|"]
        out += [f"| `{column}` | `{ctype}` | {notes} |" for column, ctype, notes in rows]
        if table["constraints"]:
            out += ["", "**Keys and references**", ""]
            for constraint in table["constraints"]:
                out.append(f"- `{constraint.replace('`', '')}`")

    out += ["", "## Upgrading an existing database", "",
            "`migrations/migrate_current_db.sh` applies the numbered migrations in",
            "order; each directory has its own `migrate.sh` and keeps a pre-migration",
            "dump. Back up before migrating (`deployment/backup_db.sh`).", ""]
    TARGET.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(order)} tables)")


if __name__ == "__main__":
    main()
